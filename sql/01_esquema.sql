-- Esquema EMPRESA (adaptado de Elmasri e Navathe)
-- Restrições nomeadas: a aplicação traduz cada violação em mensagem de domínio.

CREATE TABLE funcionario (
  cpf            CHAR(11) PRIMARY KEY,
  pnome          VARCHAR(15) NOT NULL,
  minicial       CHAR(1),
  unome          VARCHAR(15) NOT NULL,
  datanasc       DATE,
  endereco       VARCHAR(60),
  sexo           CHAR(1),
  salario        NUMERIC(10,2) NOT NULL,
  cpf_supervisor CHAR(11),
  dnr            INT,
  CONSTRAINT ck_func_cpf CHECK (cpf ~ '^[0-9]{11}$'),
  CONSTRAINT ck_func_sexo CHECK (sexo IN ('M', 'F')),
  CONSTRAINT ck_func_salario CHECK (salario > 0),
  CONSTRAINT ck_func_superv
    CHECK (cpf_supervisor <> cpf),
  CONSTRAINT fk_func_superv FOREIGN KEY (cpf_supervisor)
    REFERENCES funcionario (cpf) ON DELETE SET NULL
);

CREATE TABLE departamento (
  dnumero INT PRIMARY KEY,
  dnome VARCHAR(30) NOT NULL UNIQUE,
  cpf_gerente CHAR(11),
  data_inicio_gerente DATE,
  CONSTRAINT fk_dep_gerente
    FOREIGN KEY (cpf_gerente)
    REFERENCES funcionario (cpf)
);

-- ciclo funcionario <-> departamento: FK adiável para cargas em uma transação
ALTER TABLE funcionario
  ADD CONSTRAINT fk_func_dep
  FOREIGN KEY (dnr)
  REFERENCES departamento (dnumero)
  DEFERRABLE INITIALLY IMMEDIATE;

CREATE TABLE localizacoes_dep (
  dnumero INT REFERENCES departamento (dnumero)
          ON DELETE CASCADE,
  dlocal  VARCHAR(30),
  PRIMARY KEY (dnumero, dlocal)
);

CREATE TABLE projeto (
  projnumero INT GENERATED BY DEFAULT AS IDENTITY
             PRIMARY KEY,
  projnome   VARCHAR(30) NOT NULL UNIQUE,
  projlocal  VARCHAR(30),
  dnum       INT NOT NULL,
  CONSTRAINT fk_proj_dep FOREIGN KEY (dnum)
    REFERENCES departamento (dnumero)
);

CREATE TABLE trabalha_em (
  fcpf  CHAR(11) REFERENCES funcionario,
  pnr   INT REFERENCES projeto,
  horas NUMERIC(4,1) NOT NULL
        CHECK (horas > 0),
  PRIMARY KEY (fcpf, pnr)
);

CREATE TABLE dependente (
  fcpf            CHAR(11)
    REFERENCES funcionario ON DELETE CASCADE,
  nome_dependente VARCHAR(30),
  sexo            CHAR(1),
  datanasc        DATE,
  parentesco      VARCHAR(15),
  PRIMARY KEY (fcpf, nome_dependente)
);

-- índices para FKs, filtros e ordenações usados pela aplicação
CREATE INDEX ix_proj_dnum ON projeto (dnum);
CREATE INDEX ix_te_pnr ON trabalha_em (pnr);
CREATE INDEX ix_func_dnr_nome ON funcionario (dnr, unome, cpf);
CREATE INDEX ix_func_superv ON funcionario (cpf_supervisor);
CREATE INDEX ix_dep_gerente ON departamento (cpf_gerente);
